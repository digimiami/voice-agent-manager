def get_industry_data(industry):
    """Get industry-specific data, falling back to general."""
    if not industry:
        return INDUSTRY_DATA['general']
    key = industry.lower().strip().replace(' ', '-')
    # Try alias mapping first
    if key in INDUSTRY_ALIASES:
        return INDUSTRY_DATA[INDUSTRY_ALIASES[key]]
    # Try direct match
    if key in INDUSTRY_DATA:
        return INDUSTRY_DATA[key]
    # Try partial match
    for k, v in INDUSTRY_DATA.items():
        if k in key or key in k:
            return v
    return INDUSTRY_DATA['general']


